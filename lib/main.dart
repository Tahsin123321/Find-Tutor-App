import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'auth_gate.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'login.dart';
import 'pdf_list_screen.dart';
import 'signup.dart';

Future<void> main() async {
  // Must run before any plugin (Firebase, etc.) is used.
  WidgetsFlutterBinding.ensureInitialized();

  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // DataRepository/SharedPreferences is no longer used: Step 5 moved posts
  // to Firestore and Step 6 moved admin review to Firestore too.

  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      title: 'Tuition Manager',
      theme: ThemeData(
        colorSchemeSeed: Colors.blue,
        useMaterial3: true,
      ),
      // AuthGate picks login or the role dashboard on startup.
      home: const AuthGate(),
      routes: {
        '/login': (context) => const LoginPage(),
        '/signup': (context) => const SignupPage(),
        '/pdf_list': (context) => PdfListScreen(),
      },
    );
  }
}
